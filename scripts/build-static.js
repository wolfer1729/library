// Builds the server-less website version (for GitHub Pages) into dist/:
//   • the app (public/), unchanged
//   • books/catalog.json, books/audio.json and books/text/<id>.json (from the downloaded books)
//   • sw.js, a service worker so the site works offline once installed on a phone
// Run "npm run download" first so every book text is saved.
// Usage: node scripts/build-static.js
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { splitPlainText } from '../public/js/textproc.js';
import { gutenbergUrl } from '../server/gutenberg.js';
import { wikisourceUrl } from '../server/wikisource.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist');
const CACHE = path.join(ROOT, 'data', 'cache');

const readJSON = (p) => fs.readFile(p, 'utf8').then(JSON.parse, () => null);
const writeJSON = (p, data) => fs.writeFile(p, JSON.stringify(data));

async function walk(dir, base = dir) {
  const out = [];
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p, base)));
    else out.push(path.relative(base, p).split(path.sep).join('/'));
  }
  return out;
}

function serviceWorker(version, shell) {
  return `// Generated by scripts/build-static.js — keeps the library working offline.
const VERSION = ${JSON.stringify(version)};
const SHELL = ${JSON.stringify(shell)};
const SHELL_CACHE = 'shell-' + VERSION;
const BOOK_CACHE = 'books-v1';
const DATA_CACHE = 'data-v1';

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL_CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('shell-') && k !== SHELL_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // e.g. LibriVox audio streams

  if (url.pathname.includes('/books/text/')) {
    // Book texts: from this device if saved, otherwise download and keep.
    e.respondWith(caches.open(BOOK_CACHE).then(async (c) => {
      const hit = await c.match(req);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok) c.put(req, res.clone());
      return res;
    }));
    return;
  }
  if (url.pathname.endsWith('/books/catalog.json') || url.pathname.endsWith('/books/audio.json')) {
    // Lists: newest from the network, the saved copy when offline.
    e.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(DATA_CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => caches.match(req)),
    );
    return;
  }
  // The app itself: installed with the service worker.
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`;
}

async function main() {
  await fs.rm(OUT, { recursive: true, force: true });
  await fs.cp(path.join(ROOT, 'public'), OUT, { recursive: true });
  await fs.writeFile(path.join(OUT, '.nojekyll'), ''); // serve files as-is (no Jekyll processing)

  const catalogDir = path.join(ROOT, 'data', 'catalog');
  const genres = JSON.parse(await fs.readFile(path.join(catalogDir, 'genres.json'), 'utf8'));
  const books = [];
  for (const f of (await fs.readdir(catalogDir)).filter((x) => x.endsWith('.json') && x !== 'genres.json').sort()) {
    const data = JSON.parse(await fs.readFile(path.join(catalogDir, f), 'utf8'));
    for (const b of data.books) {
      const book = { lang: data.lang, ...b };
      if (Array.isArray(book.text)) book.text = book.text.join('\n\n');
      books.push(book);
    }
  }

  const textDir = path.join(OUT, 'books', 'text');
  await fs.mkdir(textDir, { recursive: true });
  const audio = {};
  const missing = [];
  const out = [];
  let textBytes = 0;
  for (const b of books) {
    let chapters = null;
    if (b.text) chapters = splitPlainText(b.text);
    else if (b.source) chapters = (await readJSON(path.join(CACHE, 'content', `${b.id}.json`)))?.chapters || null;
    if (b.source && !chapters?.length) missing.push(b.id);
    if (chapters?.length) {
      const json = JSON.stringify({ chapters });
      textBytes += Buffer.byteLength(json);
      await fs.writeFile(path.join(textDir, `${b.id}.json`), json);
    }
    const lv = await readJSON(path.join(CACHE, 'librivox', `${b.id}.json`));
    if (lv?.found) audio[b.id] = { title: lv.title, url: lv.url, readers: lv.readers, totaltime: lv.totaltime, tracks: lv.tracks };

    const { text, source, lv: lvOverride, ...rest } = b;
    void lvOverride;
    out.push({
      ...rest,
      hasText: Boolean(chapters?.length),
      sourceType: source?.type || (text ? 'builtin' : null),
      sourceUrl: source?.type === 'gutenberg' ? gutenbergUrl(source.id) : source?.type === 'wikisource' ? wikisourceUrl(source.lang || b.lang, source.page) : null,
      narrated: Boolean(audio[b.id]),
    });
  }
  await writeJSON(path.join(OUT, 'books', 'catalog.json'), { genres, books: out });
  await writeJSON(path.join(OUT, 'books', 'audio.json'), audio);

  const files = await walk(OUT);
  const shell = files.filter((f) => !f.startsWith('books/') && f !== 'sw.js' && f !== '.nojekyll').sort();
  const hash = crypto.createHash('sha1');
  for (const f of shell) hash.update(f).update(await fs.readFile(path.join(OUT, f)));
  const version = hash.digest('hex').slice(0, 12);
  await fs.writeFile(path.join(OUT, 'sw.js'), serviceWorker(version, ['./', ...shell]));

  console.log(`Built dist/: ${out.length} catalogue entries, ${out.filter((b) => b.hasText).length} readable books (${(textBytes / 1e6).toFixed(1)} MB of text), ${Object.keys(audio).length} audiobook lists, ${shell.length} app files.`);
  if (missing.length) {
    console.log(`\n${missing.length} book(s) are not downloaded yet and will show as catalogue-only: ${missing.join(', ')}`);
    console.log('Run "npm run download" first to include them.');
  }
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
